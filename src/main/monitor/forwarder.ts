// Source of the hook forwarder. The installer writes it to <app data>/hooks/forward.cjs
// and Claude Code runs it as an exec-form command hook: command <absolute node path>, args [script, endpoint]
// (no shell on any platform, verified in the hooks docs 2026-11-17).
//
// Rules (spec 6.3): prints nothing, always exits 0, gives up fast when NEURAL OS is
// closed. It drops everything private before sending: no prompt, no tool output,
// no Claude message, only the first word of a shell command, only the host of a URL.
// For edit tools a second, synchronous hook entry (args [..., 'snap']) reads the file
// before the change (S1 AI change log); it is the only hook Claude waits for (~50 ms).

export const FORWARDER_VERSION = 4

export const FORWARDER_SOURCE = String.raw`// NEURAL OS hook forwarder v${FORWARDER_VERSION}. Generated by NEURAL OS, safe to delete.
'use strict'
const fs = require('fs'), http = require('http'), path = require('path')
const quit = () => process.exit(0)
setTimeout(quit, 4000).unref()
process.on('uncaughtException', quit)
const EDIT = { Edit: 1, Write: 1, MultiEdit: 1, NotebookEdit: 1 }
const chunks = []
let size = 0
process.stdin.on('data', (c) => { size += c.length; if (size <= 4e6) chunks.push(c) })
process.stdin.on('end', () => {
  let p
  try { p = JSON.parse(Buffer.concat(chunks).toString('utf8')) } catch (e) { return quit() }
  if (!p || typeof p !== 'object') return quit()
  const str = (v, n) => (typeof v === 'string' ? v.slice(0, n || 1000) : undefined)
  const out = {}
  for (const k of ['session_id', 'cwd', 'hook_event_name', 'tool_name', 'tool_use_id', 'agent_id', 'agent_type', 'source', 'model', 'reason', 'permission_mode', 'notification_type']) {
    const v = str(p[k]); if (v !== undefined) out[k] = v
  }
  if (typeof p.duration_ms === 'number') out.duration_ms = p.duration_ms
  // readiness rule (Appendix A): only its one marker line, never the rest of Claude's message
  if (typeof p.last_assistant_message === 'string') {
    const m = /^\s*READINESS:.*$/m.exec(p.last_assistant_message)
    if (m) out.readiness_line = m[0].trim().slice(0, 800)
    // session note line (rule v2): Claude's own one-line summary, nothing else of the message
    const n = /^\s*SESSION-NOTE:.*$/m.exec(p.last_assistant_message)
    if (n) out.note_line = n[0].trim().slice(0, 600)
    // lesson line (rule v3): one sentence Claude learned in this task
    const l = /^\s*LESSON:.*$/m.exec(p.last_assistant_message)
    if (l) out.lesson_line = l[0].trim().slice(0, 500)
  }
  const ti = p.tool_input && typeof p.tool_input === 'object' ? p.tool_input : {}
  const inp = {}
  for (const k of ['file_path', 'notebook_path', 'path']) { const v = str(ti[k], 4000); if (v) inp[k] = v }
  const cmd = str(ti.command, 4000)
  if (cmd) inp.command_word = path.basename(cmd.trim().split(/\s+/)[0] || '').slice(0, 60)
  const url = str(ti.url, 4000)
  if (url) { try { inp.url_host = new URL(url).host } catch (e) { /* not a URL */ } }
  if (typeof ti.run_in_background === 'boolean') inp.run_in_background = ti.run_in_background
  out.tool_input = inp
  // the synchronous "snap" hook handles edit tools before they run; the async hook skips them
  const snap = process.argv[3] === 'snap'
  if (out.hook_event_name === 'PreToolUse' && !!EDIT[out.tool_name] !== snap) return quit()
  // S1: the text before Claude's change, read before the edit tool runs
  const fp = inp.file_path || inp.notebook_path
  if (out.hook_event_name === 'PreToolUse' && EDIT[out.tool_name] && fp) {
    try {
      const abs = path.resolve(out.cwd || '.', fp), st = fs.statSync(abs)
      if (st.isFile() && st.size <= 1e6) out.before_text = fs.readFileSync(abs, 'utf8')
    } catch (e) { out.before_missing = true }
  }
  let ep
  try { ep = JSON.parse(fs.readFileSync(process.argv[2], 'utf8')) } catch (e) { return quit() }
  if (!ep || !ep.port || !ep.token) return quit()
  const body = Buffer.from(JSON.stringify(out))
  const req = http.request({ host: '127.0.0.1', port: ep.port, path: '/event', method: 'POST', timeout: 1500,
    headers: { 'content-type': 'application/json', 'content-length': body.length, 'x-neural-os': ep.token } },
    (res) => { res.resume(); res.on('end', quit) })
  req.on('error', quit)
  req.on('timeout', () => { req.destroy(); quit() })
  req.end(body)
})
process.stdin.on('error', quit)
`
